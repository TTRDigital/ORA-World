import { defineField, defineType } from "sanity";

export const siteSettings = defineType({
  name: "siteSettings",
  title: "Site settings",
  type: "document",
  groups: [
    { name: "contact", title: "Contact", default: true },
    { name: "links", title: "Links & embeds" },
    { name: "legal", title: "Legal" },
    { name: "menu", title: "Menu imagery" },
  ],
  fields: [
    defineField({
      name: "phone",
      title: "Phone",
      type: "string",
      group: "contact",
      description: "International format, e.g. +1 787 000 0000",
    }),
    defineField({
      name: "whatsapp",
      title: "WhatsApp number",
      type: "string",
      group: "contact",
      description: "Digits only with country code, e.g. 17870000000",
    }),
    defineField({ name: "email", title: "Email", type: "string", group: "contact" }),
    defineField({ name: "salesGalleryName", title: "Sales gallery name", type: "localeString", group: "contact" }),
    defineField({
      name: "salesGalleryAddress",
      title: "Sales gallery address",
      type: "localeString",
      group: "contact",
    }),
    defineField({ name: "hours", title: "Opening hours", type: "localeString", group: "contact" }),
    defineField({ name: "social", title: "Social links", type: "array", of: [{ type: "link" }], group: "contact" }),
    defineField({ name: "siteLat", title: "Site latitude", type: "number", group: "contact" }),
    defineField({ name: "siteLng", title: "Site longitude", type: "number", group: "contact" }),
    defineField({ name: "portalUrl", title: "Client portal (Log In) URL", type: "url", group: "links" }),
    defineField({ name: "bookingUrl", title: "Booking embed URL (Calendly / Cal.com)", type: "url", group: "links" }),
    defineField({
      name: "vrTourUrl",
      title: "Virtual tour embed URL (Kuula / Matterport)",
      type: "url",
      group: "links",
    }),
    defineField({
      name: "film",
      title: "Full film (MP4)",
      type: "file",
      options: { accept: "video/mp4" },
      group: "links",
    }),
    defineField({
      name: "filmYoutubeId",
      title: "Brand film YouTube id",
      type: "string",
      group: "links",
      description:
        "The 11-character id, e.g. HkIPZ9pGezA. Used as the hero background and the film lightbox when no MP4 is uploaded.",
      validation: (r) => r.regex(/^[A-Za-z0-9_-]{11}$/, { name: "YouTube id" }),
    }),
    defineField({
      name: "brochure",
      title: "Brochure PDF",
      type: "file",
      options: { accept: "application/pdf" },
      group: "links",
    }),
    defineField({
      name: "brochurePages",
      title: "Brochure pages (for the flipbook)",
      type: "array",
      of: [{ type: "figure" }],
      group: "links",
    }),
    defineField({ name: "brokerKit", title: "Broker kit PDF", type: "file", group: "links" }),
    defineField({ name: "mediaKit", title: "Media kit (ZIP/PDF)", type: "file", group: "links" }),
    defineField({
      name: "legalNotice",
      title: "Legal notice (verbatim, required)",
      type: "localeText",
      group: "legal",
      validation: (r) => r.required(),
    }),
    defineField({ name: "renderingNotice", title: "Rendering notice", type: "localeString", group: "legal" }),
    defineField({ name: "sponsor", title: "Sponsor line", type: "localeString", group: "legal" }),
    defineField({
      name: "consentText",
      title: "Lead form consent text (TCPA)",
      type: "localeText",
      group: "legal",
      validation: (r) => r.required(),
    }),
    defineField({
      name: "menuImages",
      title: "Overlay menu images",
      type: "array",
      group: "menu",
      description: "One image per primary menu item; it appears when the item is hovered.",
      of: [
        {
          type: "object",
          fields: [
            defineField({
              name: "key",
              title: "Menu item",
              type: "string",
              options: {
                list: ["residences", "floorPlans", "amenities", "lifestyle", "location", "gallery", "contact"],
              },
            }),
            defineField({ name: "image", title: "Image", type: "figure" }),
          ],
          preview: { select: { title: "key", media: "image" } },
        },
      ],
    }),
  ],
  preview: { prepare: () => ({ title: "Site settings" }) },
});
